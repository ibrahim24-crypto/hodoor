/** Semantic colors for this app, provided alongside [MaterialTheme]. */
val LocalHodoorColors = staticCompositionLocalOf { LightHodoorColors }

@Composable
fun HodoorTheme(
    darkTheme: Boolean = androidx.compose.foundation.isSystemInDarkTheme(),
    content: @Composable () -> Unit
) {
    val scheme = if (darkTheme) DarkColorScheme else LightColorScheme
    val semantic = if (darkTheme) DarkHodoorColors else LightHodoorColors
    CompositionLocalProvider(LocalHodoorColors provides semantic) {
        MaterialTheme(
            colorScheme = scheme,
            typography = Typography,
            shapes = HodoorShapes.material,
            content = content
        )
    }
}
